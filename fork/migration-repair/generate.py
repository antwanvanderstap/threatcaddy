#!/usr/bin/env python3
"""Generate repair.sql: move a database migrated by the pre-merge
feat/asset-management branch onto upstream's migration history.

That branch rewrote the journal timestamps of 0000-0019 and added its own 0020
(AgentCaddy/LLM tables) and 0021 (incident fields). Upstream's migrateDatabase
only accepts a history that is an exact prefix of its journal (hash and
timestamp), so such a database refuses to start after the merge.

repair.sql, in one transaction:
  1. verifies the history is exactly the branch's 22 entries (by hash);
  2. applies upstream 0020 in IF NOT EXISTS form, so the schema matches what
     upstream 0020 leaves behind (the branch's 0020 created the same tables
     but not all indexes and the investigation_members FK);
  3. rewrites the history to upstream 0000-0020 (hash + timestamp).
The server then applies 0021-0025 itself on start, as on any upstream install.

Run from the repo root: python3 fork/migration-repair/generate.py
"""
import hashlib, json, re, subprocess
from pathlib import Path

MIG = Path('server/src/db/migrations')
BRANCH_REV = '19adce1'  # last feat/asset-management commit before the upstream merge


def sha(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def git_show(rev: str, path: str) -> str:
    return subprocess.run(['git', 'show', f'{rev}:{path}'], check=True, capture_output=True, text=True).stdout


journal = json.loads((MIG / 'meta/_journal.json').read_text())['entries']
upstream = [(e['tag'], sha((MIG / f"{e['tag']}.sql").read_text()), e['when']) for e in journal[:21]]
assert upstream[-1][0] == '0020_runtime_schema_completion'

branch_journal = json.loads(git_show(BRANCH_REV, str(MIG / 'meta/_journal.json')))['entries']
branch = [sha(git_show(BRANCH_REV, str(MIG / f"{e['tag']}.sql"))) for e in branch_journal]
assert len(branch) == 22 and branch[:20] == [h for _, h, _ in upstream[:20]], 'branch 0000-0019 differ from upstream'


def idempotent(sql: str) -> str:
    sql = re.sub(r'ADD COLUMN "', 'ADD COLUMN IF NOT EXISTS "', sql)
    sql = re.sub(r'CREATE INDEX "', 'CREATE INDEX IF NOT EXISTS "', sql)
    sql = re.sub(r'CREATE TABLE "', 'CREATE TABLE IF NOT EXISTS "', sql)
    sql = re.sub(r'(ALTER TABLE "[a-z_]+" ADD CONSTRAINT .*?;)',
                 r'DO $$ BEGIN \1 EXCEPTION WHEN duplicate_object THEN NULL; END $$;', sql, flags=re.S)
    return sql


body = '\n'.join(line for line in (MIG / '0020_runtime_schema_completion.sql').read_text().splitlines()
                 if not line.startswith('--'))
expected = ',\n    '.join(f"'{h}'" for h in branch)
history = ',\n  '.join(f"('{h}', {when})" for _, h, when in upstream)

out = f"""-- GENERATED by fork/migration-repair/generate.py; do not edit.
-- One-time repair for a database migrated by the pre-merge feat/asset-management
-- branch. Run once, with the server stopped, before starting the merged server.
BEGIN;
SET LOCAL search_path = public;

DO $$
DECLARE actual text[];
BEGIN
  SELECT array_agg(hash ORDER BY id) INTO actual FROM drizzle.__drizzle_migrations;
  IF actual IS DISTINCT FROM ARRAY[
    {expected}
  ] THEN
    RAISE EXCEPTION 'Not a database migrated by the pre-merge branch (history %); nothing changed', actual;
  END IF;
END $$;

-- Upstream 0020, idempotent: the branch already created most of these objects.
{idempotent(body).strip()}

DELETE FROM drizzle.__drizzle_migrations;
INSERT INTO drizzle.__drizzle_migrations (hash, created_at) VALUES
  {history};

COMMIT;
"""
(Path(__file__).parent / 'repair.sql').write_text(out)
print('wrote', Path(__file__).parent / 'repair.sql')
